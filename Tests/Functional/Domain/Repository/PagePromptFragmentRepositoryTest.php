/**
 * Page tree used across these tests. tx_aim_prompt_fragment is a reusable
 * library entry with no page relation of its own; tx_aim_page_prompt_fragment
 * is the per-page assignment that carries `parent_page`:
 *
 *   1 "Has a text fragment"       -- assignment -> fragment: scope=text, prompt contains "banana"
 *   2 "Has an image fragment"     -- assignment -> fragment: scope=imageGeneration
 *   3 "No fragments"              -- no tx_aim_page_prompt_fragment rows at all
 *   4 "Two fragments"             -- two assignments (text + all) -- must appear exactly once
 *   5 "Multi-scope fragment"      -- one assignment -> fragment: scope=text,vision
 */
final class PagePromptFragmentRepositoryTest extends FunctionalTestCase
