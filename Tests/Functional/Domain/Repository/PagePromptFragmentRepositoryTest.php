    protected array $testExtensionsToLoad = [
        'b13/aim',
    ];

    protected function setUp(): void
    {
        parent::setUp();

        $pages = $this->getConnectionPool()->getConnectionForTable('pages');
        $pages->insert('pages', ['uid' => 1, 'pid' => 0, 'title' => 'Has a text fragment']);
        $pages->insert('pages', ['uid' => 2, 'pid' => 0, 'title' => 'Has an image fragment']);
        $pages->insert('pages', ['uid' => 3, 'pid' => 0, 'title' => 'No fragments']);
        $pages->insert('pages', ['uid' => 4, 'pid' => 0, 'title' => 'Two fragments']);
        $pages->insert('pages', ['uid' => 5, 'pid' => 0, 'title' => 'Multi-scope fragment']);

        $fragments = $this->getConnectionPool()->getConnectionForTable('tx_aim_prompt_fragment');
        $assignments = $this->getConnectionPool()->getConnectionForTable('tx_aim_page_prompt_fragment');

        $fragmentAUid = $this->insertFragment($fragments, 'Fragment A', 'Always mention the banana promotion.', PromptFragmentScope::Text->value);
        $this->insertAssignment($assignments, 1, $fragmentAUid);

        $fragmentBUid = $this->insertFragment($fragments, 'Fragment B', 'Add a watermark.', PromptFragmentScope::ImageGeneration->value);
        $this->insertAssignment($assignments, 2, $fragmentBUid);

        $fragmentC1Uid = $this->insertFragment($fragments, 'Fragment C1', 'Formal tone.', PromptFragmentScope::Text->value);
        // Sorting is deliberately reversed against title (C1 gets the
        // HIGHER sorting value) so a test asserting the title-alphabetical
        // order [C1, C2] and one asserting the actual assignment order
        // [C2, C1] can't be satisfied by the same, coincidentally-matching
        // fixture.
        $this->insertAssignment($assignments, 4, $fragmentC1Uid, 20);

        $fragmentC2Uid = $this->insertFragment($fragments, 'Fragment C2', 'Brand voice.', PromptFragmentScope::All->value);
        $this->insertAssignment($assignments, 4, $fragmentC2Uid, 10);

        $fragmentDUid = $this->insertFragment($fragments, 'Fragment D', 'Ask for both text and vision styling.', PromptFragmentScope::Text->value . ',' . PromptFragmentScope::Vision->value);
        $this->insertAssignment($assignments, 5, $fragmentDUid);
    }

    private function insertFragment(Connection $connection, string $title, string $prompt, string $scope): int
    {
        $connection->insert('tx_aim_prompt_fragment', [
            'pid' => 0,
            'title' => $title,
            'prompt' => $prompt,
            'scope' => $scope,
        ]);
        return (int)$connection->lastInsertId();
    }

    private function insertAssignment(Connection $connection, int $pageId, int $fragmentUid, int $sorting = 0): void
    {
        $connection->insert('tx_aim_page_prompt_fragment', [
            'pid' => $pageId,
            'parent_page' => $pageId,
            'fragment' => $fragmentUid,
            'sorting' => $sorting,
        ]);
    }

    private function repository(): PagePromptFragmentRepository
    {
        return $this->get(PagePromptFragmentRepository::class);
    }

