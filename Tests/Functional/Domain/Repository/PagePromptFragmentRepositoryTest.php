    /**
     * Regression test: neither the page-list nor the library-list query
     * added WorkspaceRestriction (it is NOT part of
     * DefaultRestrictionContainer, unlike Deleted/Hidden/Start/EndTime),
     * so a workspace-version row for an assignment or a fragment showed up
     * as a second, spurious entry alongside its own live counterpart, even
     * when resolving in the live workspace (0).
     */
    #[Test]
    public function aWorkspaceVersionedFragmentOrAssignmentDoesNotAppearTwiceInEitherListing(): void
    {
        $pages = $this->getConnectionPool()->getConnectionForTable('pages');
        $pages->insert('pages', ['uid' => 40, 'pid' => 0, 'title' => 'Workspace test page']);

        $fragments = $this->getConnectionPool()->getConnectionForTable('tx_aim_prompt_fragment');
        $fragments->insert('tx_aim_prompt_fragment', ['pid' => 0, 'title' => 'Workspace-editable fragment', 'prompt' => 'Live tone.', 'scope' => 'all']);
        $liveFragmentUid = (int)$fragments->lastInsertId();
        $fragments->insert('tx_aim_prompt_fragment', [
            'pid' => 0,
            'title' => 'Workspace-editable fragment',
            'prompt' => 'Draft tone.',
            'scope' => 'all',
            't3ver_wsid' => 3,
            't3ver_oid' => $liveFragmentUid,
        ]);
        $workspaceVersionFragmentUid = (int)$fragments->lastInsertId();

        $assignments = $this->getConnectionPool()->getConnectionForTable('tx_aim_page_prompt_fragment');
        $assignments->insert('tx_aim_page_prompt_fragment', ['pid' => 40, 'parent_page' => 40, 'fragment' => $liveFragmentUid]);
        $liveAssignmentUid = (int)$assignments->lastInsertId();
        $assignments->insert('tx_aim_page_prompt_fragment', [
            'pid' => 40,
            'parent_page' => 40,
            'fragment' => $liveFragmentUid,
            't3ver_wsid' => 3,
            't3ver_oid' => $liveAssignmentUid,
        ]);

        // setUp() already seeds pages 1-5 with their own fragments, so this
        // asserts page 40 appears exactly ONCE among the results, not that
        // it's the only result overall. Note: findByDemand()'s own
        // pre-existing distinct()/COUNT(DISTINCT pages.uid) already
        // incidentally collapses the two assignment rows onto the same
        // pages.uid=40 even without WorkspaceRestriction, so this
        // particular assertion doesn't by itself prove the restriction is
        // in effect - it's still a correct, worthwhile statement, just not
        // the one that would fail without the fix. That's the fragment-list
        // assertion below: two GENUINELY DIFFERENT tx_aim_prompt_fragment
        // rows (uid 1 live, uid 2 its own workspace-version copy) have no
        // equivalent natural collapsing, so findLibraryByDemand() returning
        // both would only be caught by WorkspaceRestriction actually being
        // applied - confirmed live: removing it made $workspaceVersionFragmentUid
        // (a genuinely separate tx_aim_prompt_fragment row, not a second
        // copy of the live one) show up in the results below. An earlier
        // version of this test asserted "the live uid appears exactly
        // once", which is true regardless of whether the fix is applied -
        // it never checks whether the SEPARATE workspace-version uid
        // is ALSO present, so it passed even with the fix removed. Assert
        // the workspace-version's own uid is absent instead.
        $repository = $this->repository();
        $pageRows = $repository->findByDemand(new PagePromptFragmentDemand(), null);
        $page40Occurrences = array_filter($pageRows, static fn(array $row): bool => (int)$row['uid'] === 40);
        self::assertCount(1, $page40Occurrences, 'Page 40 must not appear twice.');

        $fragmentRows = $repository->findLibraryByDemand(new PagePromptFragmentDemand(), null);
        $fragmentUids = array_map(static fn(array $row): int => (int)$row['uid'], $fragmentRows);
        self::assertContains($liveFragmentUid, $fragmentUids, 'The live fragment must still be listed.');
        self::assertNotContains($workspaceVersionFragmentUid, $fragmentUids, 'The workspace-version row must not appear as a separate, second fragment.');
    }

