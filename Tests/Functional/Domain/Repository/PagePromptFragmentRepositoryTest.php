    /**
     * Regression test: the Library listing used to have no page-tree
     * filtering at all - the fix adds $usagePageIds, a THIRD, separate
     * filter from the existing $accessiblePageIds access check. It answers
     * "is this fragment actually ASSIGNED somewhere in the selected
     * subtree", not "is this fragment's own storage pid one the user may
     * reach" (that remains $accessiblePageIds' job, entirely unaffected by
     * this fixture: every fragment here is stored at pid=0 regardless of
     * where it's assigned). A fragment assigned inside the subtree must
     * appear, one assigned only outside it must not, and a pid=0 fragment
     * with no assignment at all must appear regardless - global fragments
     * are exempt from tree filtering the same way they're exempt from the
     * accessible-pages check.
     */
    #[Test]
    public function findLibraryByDemandFiltersByUsageWithinTheGivenSubtreeNotByStoragePid(): void
    {
        $pages = $this->getConnectionPool()->getConnectionForTable('pages');
        $pages->insert('pages', ['uid' => 100, 'pid' => 0, 'title' => 'Subtree root']);
        $pages->insert('pages', ['uid' => 101, 'pid' => 100, 'title' => 'Subtree child']);
        $pages->insert('pages', ['uid' => 200, 'pid' => 0, 'title' => 'Outside subtree']);

        $fragments = $this->getConnectionPool()->getConnectionForTable('tx_aim_prompt_fragment');
        $assignments = $this->getConnectionPool()->getConnectionForTable('tx_aim_page_prompt_fragment');

        // Stored at a non-zero, unrelated pid (300, not inserted as a real
        // page - fine, nothing dereferences a fragment's own storage pid as
        // a foreign key here): insertFragment() always uses pid=0, which is
        // unconditionally exempt from the usage filter and would make this
        // test pass regardless of whether the filter works at all.
        $fragments->insert('tx_aim_prompt_fragment', ['pid' => 300, 'title' => 'In-subtree fragment', 'prompt' => 'Tone.', 'scope' => 'all']);
        $inSubtreeUid = (int)$fragments->lastInsertId();
        $this->insertAssignment($assignments, 101, $inSubtreeUid);

        $fragments->insert('tx_aim_prompt_fragment', ['pid' => 300, 'title' => 'Outside-subtree fragment', 'prompt' => 'Tone.', 'scope' => 'all']);
        $outsideSubtreeUid = (int)$fragments->lastInsertId();
        $this->insertAssignment($assignments, 200, $outsideSubtreeUid);

        $unassignedGlobalUid = $this->insertFragment($fragments, 'Unassigned global fragment', 'Tone.', PromptFragmentScope::All->value);

        $subtreePageIds = [100, 101];
        $rows = $this->repository()->findLibraryByDemand(new PagePromptFragmentDemand(), null, $subtreePageIds);
        $uids = array_map(static fn(array $row): int => (int)$row['uid'], $rows);

        self::assertContains($inSubtreeUid, $uids, 'A fragment assigned inside the selected subtree must appear.');
        self::assertNotContains($outsideSubtreeUid, $uids, 'A fragment assigned only outside the selected subtree must not appear.');
        self::assertContains($unassignedGlobalUid, $uids, 'An unassigned global fragment must appear regardless of tree selection.');

        self::assertSame(
            count($uids),
            $this->repository()->countLibraryByDemand(new PagePromptFragmentDemand(), null, $subtreePageIds),
            'countLibraryByDemand() must apply the identical usage filter.',
        );
    }

    /**
     * Regression test: a fragment STORED inside the selected subtree (its
     * own pid) but never actually ASSIGNED to any page there must NOT
     * appear once tree filtering is active - conflating "stored under this
     * page" with "used somewhere in this subtree" was the exact bug the
     * fix above avoids. This fragment's storage pid (101) is inside the
     * subtree, but its one real assignment (page 200) is not.
     */
    #[Test]
    public function findLibraryByDemandDoesNotMatchOnStoragePidAloneWhenFilteringByUsage(): void
    {
        $pages = $this->getConnectionPool()->getConnectionForTable('pages');
        $pages->insert('pages', ['uid' => 100, 'pid' => 0, 'title' => 'Subtree root']);
        $pages->insert('pages', ['uid' => 101, 'pid' => 100, 'title' => 'Subtree child']);
        $pages->insert('pages', ['uid' => 200, 'pid' => 0, 'title' => 'Outside subtree']);

        $fragments = $this->getConnectionPool()->getConnectionForTable('tx_aim_prompt_fragment');
        $assignments = $this->getConnectionPool()->getConnectionForTable('tx_aim_page_prompt_fragment');

        $fragments->insert('tx_aim_prompt_fragment', ['pid' => 101, 'title' => 'Stored inside, used outside', 'prompt' => 'Tone.', 'scope' => 'all']);
        $storedInsideUid = (int)$fragments->lastInsertId();
        $this->insertAssignment($assignments, 200, $storedInsideUid);

        $rows = $this->repository()->findLibraryByDemand(new PagePromptFragmentDemand(), null, [100, 101]);
        $uids = array_map(static fn(array $row): int => (int)$row['uid'], $rows);

        self::assertNotContains($storedInsideUid, $uids, 'Storage pid inside the subtree must not substitute for an actual usage there.');
    }

