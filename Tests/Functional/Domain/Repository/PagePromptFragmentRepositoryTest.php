    /**
     * Regression test: fragmentStillExists() (used by the fix above) must
     * NOT treat a merely hidden fragment as gone - unlike a deleted one, an
     * editor disabling the auto-detected fragment is still a real row an
     * in-place UPDATE can safely refresh. Detaching into a new fragment
     * here would silently undo that hidden=1 (the replacement is created
     * visible) and leave the disabled original behind as an abandoned
     * duplicate, accumulating one more on every calibration run.
     */
    #[Test]
    public function upsertAutoDetectedFragmentRefreshesAHiddenFragmentInPlaceRatherThanDetaching(): void
    {
        $fragments = $this->getConnectionPool()->getConnectionForTable('tx_aim_prompt_fragment');
        $fragments->insert('tx_aim_prompt_fragment', ['pid' => 3, 'title' => 'Tone of voice (auto-detected)', 'prompt' => 'Stale tone.', 'scope' => 'text', 'hidden' => 1]);
        $hiddenFragmentUid = (int)$fragments->lastInsertId();

        $assignments = $this->getConnectionPool()->getConnectionForTable('tx_aim_page_prompt_fragment');
        $assignments->insert('tx_aim_page_prompt_fragment', ['pid' => 3, 'parent_page' => 3, 'fragment' => $hiddenFragmentUid, 'auto_generated' => 1]);

        $fragmentUid = $this->repository()->upsertAutoDetectedFragment(3, 'Tone of voice (auto-detected)', 'Refreshed tone.', '', ['text'], AutoGeneratedFragmentSource::Cli);

        self::assertSame($hiddenFragmentUid, $fragmentUid, 'The hidden fragment must be refreshed in place, not replaced.');
        // A plain Connection::select()/count() applies the same default
        // HiddenRestriction as a QueryBuilder built via
        // getQueryBuilderForTable() - it would silently miss the very row
        // this test needs to inspect, so restrictions are removed here.
        $qb = $this->getConnectionPool()->getQueryBuilderForTable('tx_aim_prompt_fragment');
        $qb->getRestrictions()->removeAll();
        $fragmentRow = $qb->select('prompt', 'hidden')
            ->from('tx_aim_prompt_fragment')
            ->where($qb->expr()->eq('uid', $qb->createNamedParameter($hiddenFragmentUid, Connection::PARAM_INT)))
            ->executeQuery()
            ->fetchAssociative();
        self::assertSame('Refreshed tone.', $fragmentRow['prompt']);
        self::assertSame(1, (int)$fragmentRow['hidden'], "The editor's own hidden=1 must survive the refresh.");

        $countQb = $this->getConnectionPool()->getQueryBuilderForTable('tx_aim_prompt_fragment');
        $countQb->getRestrictions()->removeAll();
        $count = $countQb->count('uid')
            ->from('tx_aim_prompt_fragment')
            ->where($countQb->expr()->eq('title', $countQb->createNamedParameter('Tone of voice (auto-detected)')))
            ->executeQuery()
            ->fetchOne();
        self::assertSame(1, (int)$count, 'No abandoned duplicate fragment must be created.');
    }

