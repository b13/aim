    /**
     * Regression test: upsertAutoDetectedFragment() used to UPDATE the
     * existing auto-detected fragment's row in place on every re-run. But
     * that fragment is a real, globally-selectable library entry, so an
     * editor could reuse it on a completely different page via the suggest
     * wizard between calibration runs. The next run would then silently
     * overwrite content that other page now also relies on. It must detach
     * into a fresh fragment and repoint its own assignment instead, leaving
     * the shared fragment (and the other page using it) untouched.
     */
    #[Test]
    public function upsertAutoDetectedFragmentDetachesIntoANewFragmentInsteadOfClobberingOneReusedElsewhere(): void
    {
        $repository = $this->repository();
        $firstUid = $repository->upsertAutoDetectedFragment(3, 'Tone of voice (auto-detected)', 'First tone.', '', ['text'], AutoGeneratedFragmentSource::Cli);

        // Editor reuses the auto-detected fragment on a different page via
        // the suggest wizard, independently of the calibration workflow.
        $assignments = $this->getConnectionPool()->getConnectionForTable('tx_aim_page_prompt_fragment');
        $assignments->insert('tx_aim_page_prompt_fragment', ['pid' => 2, 'parent_page' => 2, 'fragment' => $firstUid]);

        $secondUid = $repository->upsertAutoDetectedFragment(3, 'Tone of voice (auto-detected)', 'Refreshed tone.', '', ['text'], AutoGeneratedFragmentSource::Cli);

        self::assertNotSame($firstUid, $secondUid, 'A new fragment must be created rather than overwriting the shared one.');

        $originalFragment = $this->getConnectionPool()->getConnectionForTable('tx_aim_prompt_fragment')
            ->select(['prompt'], 'tx_aim_prompt_fragment', ['uid' => $firstUid])
            ->fetchAssociative();
        self::assertSame('First tone.', $originalFragment['prompt'], 'The fragment still used by another page must keep its original content.');

        $page3Assignment = $this->getConnectionPool()->getConnectionForTable('tx_aim_page_prompt_fragment')
            ->select(['fragment'], 'tx_aim_page_prompt_fragment', ['parent_page' => 3, 'auto_generated' => 1])
            ->fetchAssociative();
        self::assertSame($secondUid, (int)$page3Assignment['fragment'], "Page 3's own auto-generated assignment must now point at the new fragment.");
        self::assertSame(
            1,
            $this->getConnectionPool()->getConnectionForTable('tx_aim_page_prompt_fragment')
                ->count('uid', 'tx_aim_page_prompt_fragment', ['parent_page' => 3, 'auto_generated' => 1]),
            'The existing assignment must be repointed, not duplicated into a second one.',
        );
    }

    /**
     * Regression test: if the auto-generated assignment's `fragment` FK is
     * 0 (e.g. the FK was never set on a hand-crafted/legacy row), updating
     * "fragment uid 0" used to silently match no rows at all - the command
     * would report success and a fresh uid, but nothing was actually ever
     * persisted anywhere reachable. It must instead create a new fragment
     * and repair the assignment's FK to point at it.
     */
    #[Test]
    public function upsertAutoDetectedFragmentRepairsAnAssignmentWhoseFragmentFkIsZero(): void
    {
        $assignments = $this->getConnectionPool()->getConnectionForTable('tx_aim_page_prompt_fragment');
        $assignments->insert('tx_aim_page_prompt_fragment', ['pid' => 3, 'parent_page' => 3, 'fragment' => 0, 'auto_generated' => 1]);

        $fragmentUid = $this->repository()->upsertAutoDetectedFragment(3, 'Tone of voice (auto-detected)', 'Repaired tone.', '', ['text'], AutoGeneratedFragmentSource::Cli);

        self::assertNotSame(0, $fragmentUid);
        $fragmentRow = $this->getConnectionPool()->getConnectionForTable('tx_aim_prompt_fragment')
            ->select(['prompt'], 'tx_aim_prompt_fragment', ['uid' => $fragmentUid])
            ->fetchAssociative();
        self::assertSame('Repaired tone.', $fragmentRow['prompt']);

        $assignmentRow = $this->getConnectionPool()->getConnectionForTable('tx_aim_page_prompt_fragment')
