/**
 * Finds `pages` records that have at least one `tx_aim_prompt_fragment`
 * assigned via a `tx_aim_page_prompt_fragment` record.
 *
 * Reads follow the workspace of the current Context. The paginated listings
 * (findByDemand(), findLibraryByDemand() and their counts) filter, sort and
 * count live records plus the ones created in that workspace, like the core
 * Records module, and overlay the rows they return. Every other read sees
 * edits, moves and deletions as well. upsertAutoDetectedFragment() writes
 * live without DataHandler and therefore reads live records only.
 */
class PagePromptFragmentRepository
{
    private const PAGES_TABLE = 'pages';
    private const ASSIGNMENT_TABLE = 'tx_aim_page_prompt_fragment';

    /**
     * Mirrors the TCA 'max' on tx_aim_prompt_fragment, which DataHandler would
     * apply; upsertAutoDetectedFragment() writes through the connection.
     */
    private const MAX_TITLE_LENGTH = 255;
    private const MAX_PROMPT_LENGTH = 4000;
    private const MAX_EXAMPLES_LENGTH = 6000;
    private const FRAGMENT_TABLE = 'tx_aim_prompt_fragment';

    public function __construct(
        private readonly ConnectionPool $connectionPool,
        private readonly Context $context,
    ) {}

    /**
     * @param list<int>|null $accessiblePageIds null = unrestricted (admin); [] must short-circuit to no results
     * @return list<array<string, mixed>>
     */
    public function findByDemand(PagePromptFragmentDemand $demand, ?array $accessiblePageIds): array
    {
        if ($accessiblePageIds === []) {
            return [];
        }
        $qb = $this->getQueryBuilderForDemand($demand, $accessiblePageIds);
        $qb->distinct()
            ->select(
                'pages.uid',
                'pages.pid',
                'pages.title',
                'pages.tx_aim_disable_inherited_fragments',
                'pages.doktype',
                'pages.is_siteroot',
                'pages.nav_hide',
                'pages.module',
                'pages.content_from_pid',
                'pages.hidden',
                'pages.starttime',
                'pages.endtime',
                'pages.fe_group',
                'pages.perms_userid',
                'pages.perms_groupid',
                'pages.perms_user',
                'pages.perms_group',
                'pages.perms_everybody',
                'pages.t3ver_oid',
                'pages.t3ver_wsid',
                'pages.t3ver_state',
            )
            ->orderBy('pages.' . $demand->getOrderField(), $demand->getOrderDirection())
            ->addOrderBy('pages.uid', 'asc')
            ->setMaxResults($demand->getLimit())
            ->setFirstResult($demand->getOffset());

        return $this->overlay(self::PAGES_TABLE, $qb->executeQuery()->fetchAllAssociative());
    }

    /**
     * @param list<int>|null $accessiblePageIds
     */
    public function countByDemand(PagePromptFragmentDemand $demand, ?array $accessiblePageIds): int
    {
        if ($accessiblePageIds === []) {
            return 0;
        }
        // The join underneath (same as findByDemand()) produces one row per
        // matching fragment, so a plain COUNT(*) would count fragments, not
        // pages. A page with 3 matching fragments would count as 3.
        // COUNT(DISTINCT pages.uid) is the correct "how many distinct pages
        // match" query.
        $qb = $this->getQueryBuilderForDemand($demand, $accessiblePageIds);
        // count() quotes its entire argument as a single identifier, so it
        // can't express "DISTINCT column", addSelectLiteral() with a raw
        // COUNT(DISTINCT ...) expression is the way around that. Safe here
        // specifically because getQueryBuilderForDemand() never calls
        // select() itself, so this is the only call that ever populates the
        // select list; RequestLogRepository's own aggregate queries instead
        // start from a QueryBuilder that already has an explicit
        // select('*'), where addSelectLiteral() would append onto that `*`
        // rather than define the select list from scratch, that's why those
        // use selectLiteral() (replaces) instead.
        $qb->addSelectLiteral('COUNT(DISTINCT ' . $qb->quoteIdentifier('pages.uid') . ')');
        return (int)$qb->executeQuery()->fetchOne();
    }

    /**
     * Adds `fragmentCount`, `scopes` (list<string>, distinct) and `fragments`
     * (list<array{uid: int, title: string, scope: string}>, the individual
     * fragments themselves, for the Preview list's own "N fragment(s)"
     * disclosure, mirroring the Library module's "used on N page(s)" one) to
     * each given page row, from follow-up queries scoped to just those
     * page ids, not the whole matching set, so this never grows with
     * total fragment/page count, only with the current result page size.
     *
     * @param list<array<string, mixed>> $pageRows
     * @return list<array<string, mixed>>
     */
    public function enrichWithFragmentSummary(array $pageRows): array
    {
        if ($pageRows === []) {
            return [];
        }
        $pageIds = array_map(static fn(array $row): int => (int)$row['uid'], $pageRows);

        // Counted like the listing, inactive assignments included. A page whose
        // only assignment is inactive would report otherwise "no fragments"
        // while holding one.
        $assignments = $this->sortAssignments($this->findInWorkspace(self::ASSIGNMENT_TABLE, 'parent_page', $pageIds));
        $fragments = $this->findFragmentsByUid(array_map(static fn(array $row): int => (int)$row['fragment'], $assignments));

        $countByPage = [];
        $scopesByPage = [];
        $fragmentsByPage = [];
        foreach ($assignments as $assignment) {
            $fragment = $fragments[(int)$assignment['fragment']] ?? null;
            if ($fragment === null) {
                continue;
            }
            $pageId = (int)$assignment['parent_page'];
            $countByPage[$pageId] = ($countByPage[$pageId] ?? 0) + 1;
            foreach (PromptFragmentScope::parseList((string)$fragment['scope']) as $scopeValue) {
                $scopesByPage[$pageId][$scopeValue] = true;
            }
            $fragmentsByPage[$pageId][] = [
                'uid' => (int)$fragment['uid'],
                'title' => (string)$fragment['title'],
                'pid' => (int)$fragment['pid'],
                'scope' => (string)$fragment['scope'],
            ];
        }

        return array_map(static function (array $pageRow) use ($countByPage, $scopesByPage, $fragmentsByPage): array {
            $pageId = (int)$pageRow['uid'];
            $pageRow['fragmentCount'] = $countByPage[$pageId] ?? 0;
            $pageRow['scopes'] = array_keys($scopesByPage[$pageId] ?? []);
            $pageRow['fragments'] = $fragmentsByPage[$pageId] ?? [];
            return $pageRow;
        }, $pageRows);
    }

    /**
     * Every assignment made directly on one specific page
     *
     * @return list<array{uid: int, inherit_to_subpages: int, title: string, scope: string, hidden: int}>
     */
    public function findAssignmentsForPage(int $pageId): array
    {
        // The module reviews and activates hidden assignments, so it has to see them, unlike PagePromptResolver.
        $assignments = $this->sortAssignments($this->findInWorkspace(self::ASSIGNMENT_TABLE, 'parent_page', [$pageId]));
        $fragments = $this->findFragmentsByUid(array_map(static fn(array $row): int => (int)$row['fragment'], $assignments));

        $result = [];
        foreach ($assignments as $assignment) {
            $fragment = $fragments[(int)$assignment['fragment']] ?? null;
            if ($fragment === null) {
                continue;
            }
            $result[] = [
                'uid' => (int)$assignment['uid'],
                'inherit_to_subpages' => (int)$assignment['inherit_to_subpages'],
                'title' => (string)$fragment['title'],
                'scope' => (string)$fragment['scope'],
                'hidden' => (int)$assignment['hidden'],
            ];
        }
        return $result;
    }

    /**
     * The single auto-detected fragment (auto_generated=1)
     * for a root page. Returns null when none exists yet.
     *
     * @return array{uid: int, title: string, prompt: string, examples: string, auto_generated_source: string, hidden: int}|null
     */
    public function findAutoDetectedFragmentForRootPage(int $rootPageId): ?array
    {
        // A freshly calibrated fragment is hidden, and this is what shows it.
        foreach ($this->findInWorkspace(self::ASSIGNMENT_TABLE, 'parent_page', [$rootPageId]) as $assignment) {
            if ((int)$assignment['auto_generated'] !== 1) {
                continue;
            }
            $fragment = $this->findFragmentsByUid([(int)$assignment['fragment']])[(int)$assignment['fragment']] ?? null;
            if ($fragment === null) {
                continue;
            }
            return [
                'uid' => (int)$fragment['uid'],
                'title' => (string)$fragment['title'],
                'prompt' => (string)$fragment['prompt'],
                'examples' => (string)$fragment['examples'],
                'auto_generated_source' => (string)$assignment['auto_generated_source'],
                'hidden' => (int)$assignment['hidden'],
            ];
        }
        return null;
    }

    /**
     * Install-wide assignment counts, used when no single page is selected.
     * Counts assignments (page usages), not library fragments.
     *
     * @return array{total: int, inherited: int}
     */
    public function countAllAssignments(): array
    {
        $assignments = $this->findAllInWorkspace(self::ASSIGNMENT_TABLE);
        return [
            'total' => count($assignments),
            'inherited' => count(array_filter($assignments, static fn(array $row): bool => (bool)$row['inherit_to_subpages'])),
        ];
    }

    /**
     * Creates or updates the single auto-detected fragment for a page
     * (marked via auto_generated=1 on the ASSIGNMENT, since that's what's
     * keyed by page now), whether the caller is aim's own aim:calibrateVoice
     * command or a consumer's own equivalent (see AutoGeneratedFragmentSource).
     * Upserts rather than appending a new assignment every run, so
     * re-running the same caller refreshes that same fragment's content
     * instead of piling up duplicates. An editor's own hand-authored
     * assignments (auto_generated=0, the default for anything created
     * through the normal edit form) are never matched or touched by this,
     * since the lookup is scoped to auto_generated=1.
     *
     * The library fragment is stored at pid=$pageId (the site's root page
     * itself): a page's own rootline always includes itself, so this
     * placement always satisfies the itemsProcFunc's "within this site
     * tree" selectability rule without any special-casing.
     *
     * $source is stored on the assignment alongside auto_generated. Re-asserted
     * on every write, including an in-place refresh of an already-existing row,
     * so it always reflects whichever caller produced the CURRENT content,
     * not just whoever created the row first.
     *
     * Bypasses DataHandler deliberately.
     */
    public function upsertAutoDetectedFragment(
        int $pageId,
        string $title,
        string $prompt,
        string $examples,
        array $scope,
        AutoGeneratedFragmentSource $source,
        bool $hidden = true,
        bool $inheritToSubpages = true,
    ): int {
        $assignmentQb = $this->connectionPool->getQueryBuilderForTable(self::ASSIGNMENT_TABLE);
        // Live rows only: this write bypasses DataHandler, so it must never
        // pick up and overwrite a workspace version of the assignment.
        $assignmentQb->getRestrictions()->add(GeneralUtility::makeInstance(WorkspaceRestriction::class, 0));
        $assignmentQb->getRestrictions()->removeByType(HiddenRestriction::class);
        $existingAssignment = $assignmentQb
            ->select('uid', 'fragment')
            ->from(self::ASSIGNMENT_TABLE)
            ->where(
                $assignmentQb->expr()->eq('parent_page', $assignmentQb->createNamedParameter($pageId, Connection::PARAM_INT)),
                $assignmentQb->expr()->eq('auto_generated', $assignmentQb->createNamedParameter(1, Connection::PARAM_INT)),
            )
            ->orderBy('uid')
            ->setMaxResults(1)
            ->executeQuery()
            ->fetchAssociative();

        // This write bypasses DataHandler, so the caps and the audit entry have to be applied here.
        $prompt = $this->capLength($prompt, self::MAX_PROMPT_LENGTH);
        $examples = $this->capLength($examples, self::MAX_EXAMPLES_LENGTH);

        $fragmentValues = [
            'title' => $this->capLength($title, self::MAX_TITLE_LENGTH),
            'prompt' => $prompt,
            'examples' => $examples,
            'scope' => implode(',', $scope),
            'tstamp' => time(),
        ];

        $fragmentConnection = $this->connectionPool->getConnectionForTable(self::FRAGMENT_TABLE);
        $assignmentConnection = $this->connectionPool->getConnectionForTable(self::ASSIGNMENT_TABLE);

        if ($existingAssignment !== false) {
            $fragmentUid = (int)$existingAssignment['fragment'];
            $assignmentUid = (int)$existingAssignment['uid'];
            // fragmentUid === 0 (FK never set) or the fragment no longer
            // existing (deleted independently, e.g. by an editor, leaving a
            // dangling non-zero FK - the realistic orphan, since nothing in
            // this codebase ever resets the FK back to 0) both mean an
            // in-place UPDATE would silently touch nothing usable, while
            // still reporting success. isFragmentSharedWithAnotherAssignment()
            // covers the other silent-corruption case: this fragment is a
            // real, globally-selectable library row, so an editor could
            // have reused it on a different page via the suggest wizard
            // since the last run. Updating it in place here would then
            // overwrite content that other page now also relies on, with
            // no warning. In any of these cases, detach into a fresh
            // fragment instead of touching the existing row, and repoint
            // this one assignment at it.
            // inherit_to_subpages is just a setting and follows the caller.
            // hidden only ever goes 1 -> 0: an explicit --activate is honoured
            // on a re-run, but a plain re-run must never re-hide an assignment
            // a human has already switched on.
            $assignmentValues = [
                'auto_generated_source' => $source->value,
                'inherit_to_subpages' => (int)$inheritToSubpages,
                'tstamp' => time(),
            ];
            if (!$hidden) {
                $assignmentValues['hidden'] = 0;
            }

            if ($fragmentUid > 0 && $this->fragmentStillExists($fragmentUid) && !$this->isFragmentSharedWithAnotherAssignment($fragmentUid, $assignmentUid)) {
                $fragmentConnection->update(self::FRAGMENT_TABLE, $fragmentValues, ['uid' => $fragmentUid]);
                $assignmentConnection->update(self::ASSIGNMENT_TABLE, $assignmentValues, ['uid' => $assignmentUid]);
                $this->logFragmentWrite($fragmentUid, $pageId, $source, $hidden ? 'refreshed' : 'refreshed and activated');
                return $fragmentUid;
            }

            $fragmentConnection->insert(self::FRAGMENT_TABLE, [
                ...$fragmentValues,
                'pid' => $pageId,
                'crdate' => time(),
            ]);
            $newFragmentUid = (int)$fragmentConnection->lastInsertId(self::FRAGMENT_TABLE);
            $assignmentConnection->update(
                self::ASSIGNMENT_TABLE,
                ['fragment' => $newFragmentUid] + $assignmentValues,
                ['uid' => $assignmentUid],
            );
            $this->logFragmentWrite($newFragmentUid, $pageId, $source, 'detached into a new fragment');
            return $newFragmentUid;
        }

        $fragmentConnection->insert(self::FRAGMENT_TABLE, [
            ...$fragmentValues,
            'pid' => $pageId,
            'crdate' => time(),
        ]);
        $fragmentUid = (int)$fragmentConnection->lastInsertId(self::FRAGMENT_TABLE);

        $assignmentConnection->insert(self::ASSIGNMENT_TABLE, [
            'pid' => $pageId,
            'parent_page' => $pageId,
            'fragment' => $fragmentUid,
            'auto_generated' => 1,
            'auto_generated_source' => $source->value,
            'inherit_to_subpages' => (int)$inheritToSubpages,
            'hidden' => (int)$hidden,
            'crdate' => time(),
            'tstamp' => time(),
        ]);
        $this->logFragmentWrite($fragmentUid, $pageId, $source, $hidden ? 'created (inactive)' : 'created (active)');

        return $fragmentUid;
    }

    private function capLength(string $value, int $max): string
    {
        return mb_strlen($value) > $max ? mb_substr($value, 0, $max) : $value;
    }

    /**
     * The only trace this write leaves, since it bypasses DataHandler. A CLI or
     * scheduler run has no backend user for writelog() to attribute an entry to,
     * and so leaves none.
     */
    private function logFragmentWrite(int $fragmentUid, int $pageId, AutoGeneratedFragmentSource $source, string $action): void
    {
        $this->getBackendUser()?->writelog(
            SystemLogType::EXTENSION,
            SystemLogGenericAction::UNDEFINED,
            SystemLogErrorClassification::MESSAGE,
            // $details_nr on v12, ignored on v13/v14.
            0,
            'AiM auto-detected prompt fragment {uid} on page {pid} was {action} by {source}',
            ['uid' => $fragmentUid, 'pid' => $pageId, 'action' => $action, 'source' => $source->value],
            self::FRAGMENT_TABLE,
            $fragmentUid,
        );
    }

    /**
     * Whether $fragmentUid is referenced by any assignment OTHER than
     * $excludeAssignmentUid, e.g. whether it has been reused on another
     * page (or a second time on the same page) since it was first created.
     */
    private function isFragmentSharedWithAnotherAssignment(int $fragmentUid, int $excludeAssignmentUid): bool
    {
        $qb = $this->connectionPool->getQueryBuilderForTable(self::ASSIGNMENT_TABLE);
        // Live rows only, like the upsert this guards: a workspace-only
        // assignment reusing $fragmentUid has no live counterpart yet and
        // must not count as "shared".
        $qb->getRestrictions()->add(GeneralUtility::makeInstance(WorkspaceRestriction::class, 0));
        // An inactive assignment is a pending reuse, which is the case this
        // guard most needs to see: missing it means a re-run rewrites the
        // shared fragment and silently replaces content awaiting review.
        $qb->getRestrictions()->removeByType(HiddenRestriction::class);
        $count = $qb->count('uid')
            ->from(self::ASSIGNMENT_TABLE)
            ->where(
                $qb->expr()->eq('fragment', $qb->createNamedParameter($fragmentUid, Connection::PARAM_INT)),
                $qb->expr()->neq('uid', $qb->createNamedParameter($excludeAssignmentUid, Connection::PARAM_INT)),
            )
            ->executeQuery()
            ->fetchOne();

        return (int)$count > 0;
    }

    /**
     * Whether $fragmentUid still refers to a real, non-deleted row - the
     * default DeletedRestriction (part of getQueryBuilderForTable()'s
     * DefaultRestrictionContainer) excludes a soft-deleted one exactly as
     * it would a hard-deleted/never-existing one. HiddenRestriction is
     * explicitly removed, matching this class's own established convention
     * (see enrichLibraryWithUsage()): a
     * fragment an editor merely disabled is still a real row an
     * in-place UPDATE can safely refresh, not an orphan needing a detach -
     * treating it as gone would silently undo the editor's own hidden=1
     * and leave it as an abandoned duplicate in the library.
     */
    private function fragmentStillExists(int $fragmentUid): bool
    {
        $qb = $this->connectionPool->getQueryBuilderForTable(self::FRAGMENT_TABLE);
        $qb->getRestrictions()->removeByType(HiddenRestriction::class);
        $count = $qb->count('uid')
            ->from(self::FRAGMENT_TABLE)
            ->where($qb->expr()->eq('uid', $qb->createNamedParameter($fragmentUid, Connection::PARAM_INT)))
            ->executeQuery()
            ->fetchOne();

        return (int)$count > 0;
    }

    /**
     * @param list<int>|null $accessiblePageIds
     */
    private function getQueryBuilderForDemand(PagePromptFragmentDemand $demand, ?array $accessiblePageIds): QueryBuilder
    {
        $qb = $this->connectionPool->getQueryBuilderForTable(self::ASSIGNMENT_TABLE);
        $qb->getRestrictions()->add(GeneralUtility::makeInstance(WorkspaceRestriction::class, $this->getWorkspaceId()));
        // The module is where a human reviews and activates an inactive
        // assignment, so it has to list one. Filtering here would hide exactly
        // the rows aim:calibrateVoice tells the operator to come and look at.
        $qb->getRestrictions()->removeByType(HiddenRestriction::class);
        $qb->from(self::ASSIGNMENT_TABLE)
            ->innerJoin(
                self::ASSIGNMENT_TABLE,
                self::PAGES_TABLE,
                self::PAGES_TABLE,
                $qb->expr()->eq(self::PAGES_TABLE . '.uid', $qb->quoteIdentifier(self::ASSIGNMENT_TABLE . '.parent_page')),
            )
            ->innerJoin(
                self::ASSIGNMENT_TABLE,
                self::FRAGMENT_TABLE,
                self::FRAGMENT_TABLE,
                $qb->expr()->eq(self::FRAGMENT_TABLE . '.uid', $qb->quoteIdentifier(self::ASSIGNMENT_TABLE . '.fragment')),
            );

        if ($demand->hasScope() && $demand->getScope() !== PromptFragmentScope::All) {
            $qb->andWhere($qb->expr()->or(
                $qb->expr()->inSet(self::FRAGMENT_TABLE . '.scope', $qb->quote(PromptFragmentScope::All->value)),
                $qb->expr()->inSet(self::FRAGMENT_TABLE . '.scope', $qb->quote($demand->getScope()->value)),
            ));
        }

        if ($demand->hasSearch()) {
            $escaped = '%' . $qb->escapeLikeWildcards($demand->getSearch()) . '%';
            $qb->andWhere($qb->expr()->or(
                $qb->expr()->like(self::FRAGMENT_TABLE . '.prompt', $qb->createNamedParameter($escaped)),
                $qb->expr()->like(self::FRAGMENT_TABLE . '.examples', $qb->createNamedParameter($escaped)),
                $qb->expr()->like(self::FRAGMENT_TABLE . '.title', $qb->createNamedParameter($escaped)),
            ));
        }

        if ($accessiblePageIds !== null) {
            $qb->andWhere($qb->expr()->in(
                'pages.uid',
                $qb->createNamedParameter($accessiblePageIds, Connection::PARAM_INT_ARRAY),
            ));
        }

        return $qb;
    }

    /**
     * Library listing: every reusable fragment (not the pages that use
     * them), for browsing/reuse rather than per-page management. Restricted
     * to fragments at pid=0 (global) or within the current user's
     * accessible pages for non-admins. A strict subset of what the
     * fragment picker's own itemsProcFunc would allow (that additionally
     * allows any page within an accessible site's tree, not just pages
     * literally in the accessible-id list), so this can only under-show,
     * never leak a fragment a restricted user couldn't otherwise reach.
     *
     * @param list<int>|null $accessiblePageIds
     * @param list<int>|null $usagePageIds
     * @return list<array<string, mixed>>
     */
    public function findLibraryByDemand(PagePromptFragmentDemand $demand, ?array $accessiblePageIds, ?array $usagePageIds = null): array
    {
        // Unlike findByDemand()/countByDemand() above, an empty
        // $accessiblePageIds must NOT short-circuit here: pid=0 (global)
        // fragments stay visible regardless of how many pages the user can
        // reach (see getLibraryQueryBuilderForDemand()'s own "pid = 0 OR pid
        // IN (...)". The same rule PromptFragmentSuggestReceiver enforces
        // for the suggest wizard). Short-circuiting to [] here would hide
        // those global fragments from a restricted user with zero
        // accessible pages, when the query itself would still show them.
        $qb = $this->getLibraryQueryBuilderForDemand($demand, $accessiblePageIds, $usagePageIds);
        $qb->select('uid', 'pid', 'title', 'prompt', 'examples', 'scope', 'hidden', 't3ver_oid', 't3ver_wsid', 't3ver_state')
            ->orderBy($demand->getOrderField(), $demand->getOrderDirection())
            ->addOrderBy('uid', 'asc')
            ->setMaxResults($demand->getLimit())
            ->setFirstResult($demand->getOffset());

        return $this->overlay(self::FRAGMENT_TABLE, $qb->executeQuery()->fetchAllAssociative());
    }

    /**
     * @param list<int>|null $accessiblePageIds
     * @param list<int>|null $usagePageIds
     */
    public function countLibraryByDemand(PagePromptFragmentDemand $demand, ?array $accessiblePageIds, ?array $usagePageIds = null): int
    {
        $qb = $this->getLibraryQueryBuilderForDemand($demand, $accessiblePageIds, $usagePageIds);
        $qb->count('uid');
        return (int)$qb->executeQuery()->fetchOne();
    }

    /**
     * Adds `usedOnPageCount` and `usedOnPages` (list<array{uid: int, title:
     * string, pid: int, hidden: bool}>, sorted by title): which pages,
     * within what the current user may see, have an assignment pointing at
     * this fragment. Restricted to $accessiblePageIds the same way the
     * Pages listing itself is, so this never reveals whether an
     * inaccessible page also uses the fragment: a restricted user just
     * sees a possibly-shorter list, never an error or a leaked page
     * reference.
     *
     * Deliberately bypasses the `pages` table's own hidden/start/end-time
     * restrictions; a deleted page, and so an orphaned assignment whose
     * parent_page no longer exists, is not counted.
     *
     * One page can (rarely) have more than one assignment pointing at the
     * same fragment (e.g. two assignments with different scopes); such a
     * page is listed and counted once, not twice.
     *
     * `usedOnPageCount` is the true total, `usedOnPages` is capped to
     * $maxPagesShown per fragment. The assignments and pages of the
     * fragments given are read once for all of them: only the fragments on
     * one demanded page of the listing are passed in.
     *
     * @param list<array<string, mixed>> $fragmentRows
     * @param list<int>|null $accessiblePageIds
     * @return list<array<string, mixed>>
     */
    public function enrichLibraryWithUsage(array $fragmentRows, ?array $accessiblePageIds, int $maxPagesShown): array
    {
        if ($fragmentRows === []) {
            return [];
        }
        if ($accessiblePageIds === []) {
            return array_map(static function (array $row): array {
                $row['usedOnPageCount'] = 0;
                $row['usedOnPages'] = [];
                return $row;
            }, $fragmentRows);
        }

        $fragmentUids = array_map(static fn(array $row): int => (int)$row['uid'], $fragmentRows);
        $accessible = $accessiblePageIds === null ? null : array_flip($accessiblePageIds);
        $pageIdsByFragment = [];
        foreach ($this->findInWorkspace(self::ASSIGNMENT_TABLE, 'fragment', $fragmentUids) as $assignment) {
            $pageId = (int)$assignment['parent_page'];
            if ($accessible === null || isset($accessible[$pageId])) {
                $pageIdsByFragment[(int)$assignment['fragment']][$pageId] = $pageId;
            }
        }
        $pages = $this->findUsagePages(array_merge([], ...array_values(array_map('array_values', $pageIdsByFragment))));

        return array_map(static function (array $row) use ($pageIdsByFragment, $pages, $maxPagesShown): array {
            $usagePages = array_values(array_intersect_key($pages, $pageIdsByFragment[(int)$row['uid']] ?? []));
            $row['usedOnPageCount'] = count($usagePages);
            $row['usedOnPages'] = array_slice($usagePages, 0, $maxPagesShown);
            return $row;
        }, $fragmentRows);
    }

    /**
     * @param list<int> $pageIds
     * @return array<int, array{uid: int, pid: int, title: string, hidden: bool, doktype: int, is_siteroot: bool, starttime: int, endtime: int, nav_hide: bool, fe_group: string, module: string, content_from_pid: int}> keyed by page uid, sorted by title
     */
    private function findUsagePages(array $pageIds): array
    {
        if ($pageIds === []) {
            return [];
        }
        $qb = $this->connectionPool->getQueryBuilderForTable(self::PAGES_TABLE);
        $qb->getRestrictions()
            ->removeAll()
            ->add(GeneralUtility::makeInstance(DeletedRestriction::class))
            ->add(GeneralUtility::makeInstance(WorkspaceRestriction::class, $this->getWorkspaceId()));
        $rows = $qb->select('uid', 'pid', 'title', 'hidden', 'doktype', 'is_siteroot', 'starttime', 'endtime', 'nav_hide', 'fe_group', 'module', 'content_from_pid', 't3ver_oid', 't3ver_wsid', 't3ver_state')
            ->from(self::PAGES_TABLE)
            ->where($qb->expr()->in('uid', $qb->createNamedParameter(array_values(array_unique($pageIds)), Connection::PARAM_INT_ARRAY)))
            ->executeQuery()
            ->fetchAllAssociative();
        $rows = $this->overlay(self::PAGES_TABLE, $rows);
        usort($rows, static fn(array $a, array $b): int => [(string)$a['title'], (int)$a['uid']] <=> [(string)$b['title'], (int)$b['uid']]);

        $pages = [];
        foreach ($rows as $row) {
            $pages[(int)$row['uid']] = [
                'uid' => (int)$row['uid'],
                'pid' => (int)$row['pid'],
                'title' => (string)$row['title'],
                'hidden' => (bool)$row['hidden'],
                'doktype' => (int)$row['doktype'],
                'is_siteroot' => (bool)$row['is_siteroot'],
                'starttime' => (int)$row['starttime'],
                'endtime' => (int)$row['endtime'],
                'nav_hide' => (bool)$row['nav_hide'],
                'fe_group' => (string)$row['fe_group'],
                'module' => (string)$row['module'],
                'content_from_pid' => (int)$row['content_from_pid'],
            ];
        }
        return $pages;
    }

    /**
     * @param list<int>|null $accessiblePageIds
     * @param list<int>|null $usagePageIds Page-tree selection filter (see
     *   PromptManagementController::renderLibraryView()'s docblock):
     *   restricts to fragments actually ASSIGNED somewhere in these pages,
     *   via a separate EXISTS-style subquery against the assignment table -
     *   deliberately not folded into the $accessiblePageIds OR-clause below,
     *   which answers a different question (is this fragment's own storage
     *   pid one the user may reach at all). A global (pid=0) fragment is
     *   exempt from both: always visible regardless of tree selection.
     */
    private function getLibraryQueryBuilderForDemand(PagePromptFragmentDemand $demand, ?array $accessiblePageIds, ?array $usagePageIds = null): QueryBuilder
    {
        $qb = $this->connectionPool->getQueryBuilderForTable(self::FRAGMENT_TABLE);
        $qb->getRestrictions()
            ->removeAll()
            ->add(GeneralUtility::makeInstance(DeletedRestriction::class))
            ->add(GeneralUtility::makeInstance(WorkspaceRestriction::class, $this->getWorkspaceId()));
        $qb->from(self::FRAGMENT_TABLE);

        if ($demand->hasScope() && $demand->getScope() !== PromptFragmentScope::All) {
            $qb->andWhere($qb->expr()->or(
                $qb->expr()->inSet('scope', $qb->quote(PromptFragmentScope::All->value)),
                $qb->expr()->inSet('scope', $qb->quote($demand->getScope()->value)),
            ));
        }

        if ($demand->hasSearch()) {
            $escaped = '%' . $qb->escapeLikeWildcards($demand->getSearch()) . '%';
            $qb->andWhere($qb->expr()->or(
                $qb->expr()->like('prompt', $qb->createNamedParameter($escaped)),
                $qb->expr()->like('examples', $qb->createNamedParameter($escaped)),
                $qb->expr()->like('title', $qb->createNamedParameter($escaped)),
            ));
        }

        if ($accessiblePageIds !== null) {
            $qb->andWhere($qb->expr()->or(
                $qb->expr()->eq('pid', $qb->createNamedParameter(0, Connection::PARAM_INT)),
                $qb->expr()->in('pid', $qb->createNamedParameter($accessiblePageIds, Connection::PARAM_INT_ARRAY)),
            ));
        }

        if ($usagePageIds !== null) {
            $usageSubQuery = $this->connectionPool->getQueryBuilderForTable(self::ASSIGNMENT_TABLE);
            $usageSubQuery->getRestrictions()->add(GeneralUtility::makeInstance(WorkspaceRestriction::class, $this->getWorkspaceId()));
            $usageSubQuery->getRestrictions()->removeByType(HiddenRestriction::class);
            $usageSubQuery->select('fragment')
                ->from(self::ASSIGNMENT_TABLE)
                ->where($qb->expr()->in(
                    'parent_page',
                    $qb->createNamedParameter($usagePageIds, Connection::PARAM_INT_ARRAY),
                ));
            $qb->andWhere($qb->expr()->or(
                $qb->expr()->eq('pid', $qb->createNamedParameter(0, Connection::PARAM_INT)),
                $qb->expr()->in('uid', $usageSubQuery->getSQL()),
            ));
        }

        return $qb;
    }

    /**
     * @param list<int> $fragmentUids
     * @return array<int, array<string, mixed>> keyed by fragment uid
     */
    private function findFragmentsByUid(array $fragmentUids): array
    {
        $fragments = [];
        foreach ($this->findInWorkspace(self::FRAGMENT_TABLE, 'uid', $fragmentUids) as $fragment) {
            $fragments[(int)$fragment['uid']] = $fragment;
        }
        return $fragments;
    }

    /**
     * Rows of $table whose $column holds one of $values as the current
     * workspace sees them: edited, moved, activated, deactivated, deleted
     * or created there. Hidden rows are included. A workspace version can
     * hold a value its live row does not, so the candidates are looked up
     * across the versions as well, then read again as live or new rows,
     * overlaid and checked once more.
     *
     * @param list<int> $values
     * @return list<array<string, mixed>> ordered by uid
     */
    private function findInWorkspace(string $table, string $column, array $values): array
    {
        $values = array_values(array_unique($values));
        if ($values === []) {
            return [];
        }

        $candidateQueryBuilder = $this->getQueryBuilderInWorkspace($table, true);
        $candidates = $candidateQueryBuilder->select('uid', 't3ver_oid')
            ->from($table)
            ->where($candidateQueryBuilder->expr()->in($column, $candidateQueryBuilder->createNamedParameter($values, Connection::PARAM_INT_ARRAY)))
            ->executeQuery()
            ->fetchAllAssociative();
        $uids = array_values(array_unique(array_map(
            static fn(array $row): int => (int)$row['t3ver_oid'] > 0 ? (int)$row['t3ver_oid'] : (int)$row['uid'],
            $candidates,
        )));
        if ($uids === []) {
            return [];
        }

        $queryBuilder = $this->getQueryBuilderInWorkspace($table, false);
        $rows = $queryBuilder->select('*')
            ->from($table)
            ->where($queryBuilder->expr()->in('uid', $queryBuilder->createNamedParameter($uids, Connection::PARAM_INT_ARRAY)))
            ->orderBy('uid')
            ->executeQuery()
            ->fetchAllAssociative();

        return array_values(array_filter(
            $this->overlay($table, $rows),
            static fn(array $row): bool => in_array((int)$row[$column], $values, true),
        ));
    }

    /**
     * @return list<array<string, mixed>> ordered by uid
     */
    private function findAllInWorkspace(string $table): array
    {
        $queryBuilder = $this->getQueryBuilderInWorkspace($table, false);
        return $this->overlay(
            $table,
            $queryBuilder->select('*')->from($table)->orderBy('uid')->executeQuery()->fetchAllAssociative(),
        );
    }

    private function getQueryBuilderInWorkspace(string $table, bool $includeVersions): QueryBuilder
    {
        $queryBuilder = $this->connectionPool->getQueryBuilderForTable($table);
        $queryBuilder->getRestrictions()
            ->removeAll()
            ->add(GeneralUtility::makeInstance(DeletedRestriction::class))
            ->add(GeneralUtility::makeInstance(WorkspaceRestriction::class, $this->getWorkspaceId(), $includeVersions));
        return $queryBuilder;
    }

    /**
     * Overlays live and new rows with their version in the current
     * workspace and drops the ones deleted there. A move pointer is
     * skipped: the overlay of its live row already carries the move.
     *
     * @param list<array<string, mixed>> $rows
     * @return list<array<string, mixed>>
     */
    private function overlay(string $table, array $rows): array
    {
        $pageRepository = GeneralUtility::makeInstance(PageRepository::class, $this->context);
        $overlaid = [];
        foreach ($rows as $row) {
            if ((int)$row['t3ver_oid'] > 0) {
                continue;
            }
            $pageRepository->versionOL($table, $row, false, true);
            if (is_array($row)) {
                $overlaid[] = $row;
            }
        }
        return $overlaid;
    }

    /**
     * @param list<array<string, mixed>> $assignments
     * @return list<array<string, mixed>>
     */
    private function sortAssignments(array $assignments): array
    {
        usort($assignments, static fn(array $a, array $b): int => [(int)$a['sorting'], (int)$a['uid']] <=> [(int)$b['sorting'], (int)$b['uid']]);
        return $assignments;
    }

    private function getWorkspaceId(): int
    {
        return (int)$this->context->getPropertyFromAspect('workspace', 'id');
    }

    private function getBackendUser(): ?BackendUserAuthentication
    {
        return $GLOBALS['BE_USER'] ?? null;
    }
